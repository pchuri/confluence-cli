// Regenerates lib/east-asian-width-data.js, the East Asian Width ranges that
// lib/cjk-friendly-emphasis.js needs at runtime.
//
// get-east-asian-width is ESM-only, so the CommonJS runtime cannot require it
// on every Node version in the CI matrix (and Jest cannot at all before
// Node 24.9). It stays a devDependency: this script sweeps every code point
// through its public API and writes the ranges as plain CommonJS data.
//
// Usage: node scripts/generate-east-asian-width.js
