function collectRanges(eastAsianWidthType) {
  const ranges = Object.fromEntries(WANTED.map((k) => [k, []]));
  let current = null;
  let start = 0;
  const flush = (end) => {
    if (current && ranges[current]) ranges[current].push(start, end);
  };
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const type = eastAsianWidthType(cp);
    if (type !== current) {
      flush(cp - 1);
      current = type;
      start = cp;
    }
  }
  flush(0x10ffff);
  return ranges;
}

function format(nums) {
  const lines = [];
  for (let i = 0; i < nums.length; i += 12) {
    lines.push('    ' + nums.slice(i, i + 12).map((n) => '0x' + n.toString(16)).join(', ') + ',');
  }
  return lines.join('\n');
}

async function main() {
  const { eastAsianWidthType } = await import('get-east-asian-width');
  // The package exports no ./package.json, so read it from node_modules.
  const pkgFile = path.join(__dirname, '..', 'node_modules', 'get-east-asian-width', 'package.json');
  const { version } = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
  const ranges = collectRanges(eastAsianWidthType);
  const out = `// Generated by scripts/generate-east-asian-width.js from get-east-asian-width
// ${version}. Do not edit by hand. The data is derived from that package, whose
// license notice this file keeps:
//
// MIT License
//
// Copyright (c) Sindre Sorhus <sindresorhus@gmail.com> (https://sindresorhus.com)
//
${MIT_NOTICE}
//
// Flat arrays of inclusive [start, end] code point pairs, sorted ascending.
// Code points in none of these ranges are Narrow or Neutral.
'use strict';

module.exports = {
${WANTED.map((k) => `  ${k}: [\n${format(ranges[k])}\n  ],`).join('\n')}
};
`;
  const target = path.join(__dirname, '..', 'lib', 'east-asian-width-data.js');
  fs.writeFileSync(target, out);
  console.log(`wrote ${target} (get-east-asian-width ${version})`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
